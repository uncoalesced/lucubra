"""Header audit.

Rules:
  1. Every source code file carries the SPDX line and the provenance comment
     within its first lines, and the provenance text appears exactly once.
  2. No other file contains the provenance text or a generated-by banner.

The phrases are assembled from parts so that this file satisfies rule 1.
Exit status is 0 when the tree is clean and 1 when a violation is found.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

SPDX = "SPDX-License-Identifier: Apache-2.0"
PROVENANCE = "Engineered by " + "uncoalesced"
BANNER = "Generated by " + "Lucubra"

COMMENT_PREFIX = {
    ".rs": "//",
    ".js": "//",
    ".mjs": "//",
    ".ts": "//",
    ".py": "#",
    ".ps1": "#",
    ".sh": "#",
}
HEADER_WINDOW = 5
SKIP_DIRS = {
    ".git",
    ".venv",
    "target",
    "dist",
    "node_modules",
    "__pycache__",
    ".pytest_cache",
    ".ruff_cache",
}


def list_files(root: Path) -> list[Path]:
    """Return tracked and untracked, non-ignored files; walk the tree outside git."""
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-co", "--exclude-standard", "-z"],
            capture_output=True,
            check=True,
        ).stdout
        names = [n for n in out.decode("utf-8").split("\0") if n]
        return sorted(root / n for n in names if (root / n).is_file())
    except (OSError, subprocess.CalledProcessError):
        found = []
        for folder, dirs, files in os.walk(root):
            dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
            found.extend(Path(folder) / f for f in files)
        return sorted(found)


def count(text: str, needle: str) -> int:
    return text.lower().count(needle.lower())


def check_file(path: Path) -> tuple[bool, list[str]]:
    """Return (is_source, problems) for one file. Binary files have no problems."""
    data = path.read_bytes()
    if b"\0" in data[:8192]:
        return False, []
    text = data.decode("utf-8", errors="replace")
    prefix = COMMENT_PREFIX.get(path.suffix.lower())
    problems = []
    if prefix is None:
        for needle, label in ((PROVENANCE, "provenance text"), (BANNER, "generated-by banner")):
            if count(text, needle):
                problems.append(f"{label} in a non-source file")
        return False, problems
    head = [line.strip() for line in text.splitlines()[:HEADER_WINDOW]]
    if f"{prefix} {SPDX}" not in head:
        problems.append("missing SPDX line")
    if f"{prefix} {PROVENANCE}" not in head:
        problems.append("missing provenance comment")
    occurrences = count(text, PROVENANCE)
    if occurrences > 1:
        problems.append(f"provenance text appears {occurrences} times")
    if count(text, BANNER):
        problems.append("generated-by banner")
    return True, problems


def audit(root: Path) -> tuple[list[str], int, int]:
    """Return (violations, source file count, other file count)."""
    violations, sources, others = [], 0, 0
    for path in list_files(root):
        is_source, problems = check_file(path)
        sources += is_source
        others += not is_source
        rel = path.relative_to(root).as_posix()
        violations.extend(f"{rel}: {problem}" for problem in problems)
    return violations, sources, others


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = parser.parse_args(argv)
    violations, sources, others = audit(args.root.resolve())
    for line in violations:
        print(f"FAIL {line}")
    status = "FAILED" if violations else "ok"
    print(
        f"header audit {status}: {sources} source files, {others} other files, "
        f"{len(violations)} violations"
    )
    return 1 if violations else 0


if __name__ == "__main__":
    sys.exit(main())
